export function getStateById(id: string): StateData | undefined {
  return STATES_DATA.find((s) => s.id === id);
}

export function getDistrictById(stateId: string, districtId: string): District | undefined {
  const state = getStateById(stateId);
  return state?.districts.find((d) => d.id === districtId);
}

export function getStatesByZone(zone: string): StateData[] {
  if (!zone || zone === 'All') return STATES_DATA;
  return STATES_DATA.filter((s) => s.zone === zone);
}

